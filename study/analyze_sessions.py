#!/usr/bin/env python3
"""
analyze_sessions.py - offline analyzer for the CANIS event log
==============================================================
Turns the dashboard's append-only JSONL event log (schema:
dashboard/event_log.py) into the per-session metrics table the
longitudinal study needs (study/STUDY_PROTOCOL.md):

  duration, state occupancy (CALM/AROUSAL/CORRECTION seconds), corrections
  entered, treats dispensed, jams, zone episodes + total zone time, latency
  from session start to first zone sighting, link gaps, reboots, exposure
  levels used.

The aggregation itself lives in dashboard/event_log.py (summarize_sessions)
so the dashboard's /export/sessions.csv and this offline tool can NEVER
disagree - one implementation, two entry points. Stdlib only (no pandas).

Usage:
  python3 analyze_sessions.py events.jsonl                 # print table
  python3 analyze_sessions.py events.jsonl --csv out.csv   # also write CSV
  python3 analyze_sessions.py --generate-example ex.jsonl  # write a SYNTHETIC
                                                           # example log, then
                                                           # analyze it

The generated example is CLEARLY MARKED SYNTHETIC (a meta event on line 1 and
"SYNTHETIC" session_ids). It exists so the pipeline can be exercised before
any real session has been run. It is NOT data and must never be presented as
observations of the dog.
"""

import argparse
import json
import os
import sys

# The canonical event schema + aggregation live with the dashboard.
_DASH = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "dashboard"))
if _DASH not in sys.path:
    sys.path.insert(0, _DASH)
import event_log as elog       # noqa: E402
import canis_config as cfg     # noqa: E402


# ---------------------------------------------------------------------------
# SYNTHETIC example generator - for pipeline testing only.
# ---------------------------------------------------------------------------
def generate_example(path):
    """Write a deterministic, clearly-synthetic example event log.

    Two fake 'sessions' whose event patterns exercise every aggregation path
    (transitions, treats, a jam, zone episodes, a link gap, an exposure
    change). Deterministic on purpose: this is test scaffolding, not data.
    """
    from datetime import datetime, timezone

    def evt(ts, session, etype, **fields):
        e = {"ts": round(ts, 3),
             "iso": datetime.fromtimestamp(ts, timezone.utc).isoformat(timespec="milliseconds"),
             "session_id": session,
             "type": etype}
        e.update(fields)
        return e

    t0 = 1750000000.0  # fixed epoch -> deterministic output
    s1, s2 = "SYNTHETIC-example-A", "SYNTHETIC-example-B"
    events = [
        # line 1: explicit marker that this whole file is synthetic
        evt(t0, s1, "meta", synthetic=True,
            note="SYNTHETIC EXAMPLE - generated by analyze_sessions.py "
                 "--generate-example for pipeline testing. NOT real data."),
        evt(t0, s1, "session_start"),
        # dog enters the zone ~40 s in; sighted at ~1 Hz for 8 s (one episode)
        *[evt(t0 + 40 + i, s1, "zone_seen", zone="kitchen-left") for i in range(8)],
        evt(t0 + 42, s1, "state_transition", **{"from": "CALM", "to": "AROUSAL", "arousal": 21.0}),
        evt(t0 + 45, s1, "state_transition", **{"from": "AROUSAL", "to": "CORRECTION", "arousal": 70.4}),
        # dog leaves; decay brings it back down; leaving-reward fires
        evt(t0 + 53, s1, "state_transition", **{"from": "CORRECTION", "to": "AROUSAL", "arousal": 58.9}),
        evt(t0 + 57, s1, "state_transition", **{"from": "AROUSAL", "to": "CALM", "arousal": 11.6}),
        evt(t0 + 58, s1, "treat_dispensed", reward_count=1),
        # a second, shorter zone episode (>3 s gap => new episode), no correction
        *[evt(t0 + 120 + i, s1, "zone_seen", zone="kitchen-center") for i in range(3)],
        evt(t0 + 121, s1, "state_transition", **{"from": "CALM", "to": "AROUSAL", "arousal": 20.3}),
        evt(t0 + 127, s1, "state_transition", **{"from": "AROUSAL", "to": "CALM", "arousal": 11.9}),
        evt(t0 + 128, s1, "treat_dispensed", reward_count=2),
        # sustained-calm reward near the end
        evt(t0 + 170, s1, "treat_dispensed", reward_count=3),
        evt(t0 + 180, s1, "session_start_end_marker_ignored"),  # unknown types are tolerated

        # session B: exposure raised to 1, one jam, one link gap
        evt(t0 + 86400, s2, "session_start"),
        evt(t0 + 86410, s2, "exposure_change", **{"from": 0, "to": 1}),
        *[evt(t0 + 86430 + i, s2, "zone_seen", zone="kitchen-right") for i in range(5)],
        evt(t0 + 86432, s2, "state_transition", **{"from": "CALM", "to": "AROUSAL", "arousal": 22.0}),
        evt(t0 + 86435, s2, "state_transition", **{"from": "AROUSAL", "to": "CORRECTION", "arousal": 71.2}),
        evt(t0 + 86446, s2, "state_transition", **{"from": "CORRECTION", "to": "CALM", "arousal": 10.8}),
        evt(t0 + 86447, s2, "dispenser_jam", jam_count=1),   # treat requested, drop not confirmed
        evt(t0 + 86500, s2, "link_gap", gap_sec=12.4),
        evt(t0 + 86520, s2, "treat_dispensed", reward_count=1),
    ]
    with open(path, "w", encoding="utf-8") as f:
        for e in events:
            f.write(json.dumps(e, separators=(",", ":")) + "\n")
    print(f"wrote SYNTHETIC example log: {path}  ({len(events)} events)")
    return path


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------
def print_table(summaries):
    if not summaries:
        print("no sessions found in the log")
        return
    cols = elog.SESSION_CSV_FIELDS
    widths = {c: max(len(c), *(len(str(s.get(c, ""))) for s in summaries)) for c in cols}
    header = "  ".join(c.ljust(widths[c]) for c in cols)
    print(header)
    print("-" * len(header))
    for s in summaries:
        print("  ".join(str(s.get(c, "")).ljust(widths[c]) for c in cols))


def write_csv(summaries, path):
    import csv
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=elog.SESSION_CSV_FIELDS, extrasaction="ignore")
        w.writeheader()
        for s in summaries:
            w.writerow(s)
    print(f"wrote {path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("logfile", nargs="?", help="events.jsonl from the dashboard")
    ap.add_argument("--csv", metavar="OUT", help="also write the summary as CSV")
    ap.add_argument("--generate-example", metavar="PATH",
                    help="write a SYNTHETIC example log to PATH, then analyze it")
    args = ap.parse_args()

    if args.generate_example:
        args.logfile = generate_example(args.generate_example)
    if not args.logfile:
        ap.error("give a logfile (or --generate-example PATH)")

    events = elog.read_events(args.logfile)
    synthetic = any(e.get("synthetic") for e in events)
    if synthetic:
        print("\n*** SYNTHETIC EXAMPLE DATA - pipeline test only, not observations ***\n")

    summaries = elog.summarize_sessions(events, zone_gap_s=cfg.ZONE_EPISODE_GAP_S)
    print_table(summaries)
    if synthetic:
        print("\n*** SYNTHETIC EXAMPLE DATA - pipeline test only, not observations ***")

    if args.csv:
        write_csv(summaries, args.csv)


if __name__ == "__main__":
    main()
